"""Writes assets.toml, the recipe the loader follows to build Twilight Forest's art from the player's own jar.

Run from the port folder with the jar the recipe pins: python3 -I tools/recipe.py <TwilightForest-2.4.3.jar>
The port names every texture in lower case, so folders holding mixed case files are listed file by file.
"""

import hashlib
import re
import sys
import zipfile
from pathlib import Path

RECIPE = Path(__file__).resolve().parent.parent / "assets.toml"
MODID = "twilightforest"
PREFIX = "assets/twilightforest/"
LANG = PREFIX + "lang/en_US.lang"

# jar folder -> port folder, anything else keeps its path
FOLDERS = [
    ("textures/blocks/", "textures/block/"),
    ("textures/items/", "textures/item/"),
]
COPIED = (".png", ".ogg", ".wav", ".mcmeta")
# keys the modport extractor gave the tile.<modid>.<name>.name form, every other key gets the modid in front
LEGACY_NAME = re.compile(r"^(tile|item|entity)\.(?:[a-z0-9_]+[.:])?([a-z0-9_.]+)\.name$")


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def target(rest: str) -> str:
    for source, mapped in FOLDERS:
        if rest.startswith(source):
            return mapped + rest[len(source):]
    return rest


# second level folder a file sits in, or the file itself when it sits higher
def group(rest: str) -> str:
    parts = rest.split("/")
    return "/".join(parts[:2]) if len(parts) > 2 else rest


def copies(names: list[str]) -> list[str]:
    files = [name[len(PREFIX):] for name in names if name.startswith(PREFIX) and name.endswith(COPIED)]
    folders = {}
    for rest in files:
        folders.setdefault(group(rest), []).append(rest)
    lines = []
    for folder, members in sorted(folders.items()):
        others = [name[len(PREFIX):] for name in names if name.startswith(f"{PREFIX}{folder}/") and not name.endswith("/")]
        whole = all(rest == rest.lower() for rest in members) and len(others) == len(members) and folder not in members
        if whole:
            lines += ["[[copy]]", f"from = {quote(f'{PREFIX}{folder}/')}", f"to = {quote(target(folder + '/'))}", ""]
            continue
        for rest in sorted(members):
            lines += ["[[copy]]", f"from = {quote(PREFIX + rest)}", f"to = {quote(target(rest).lower())}", ""]
    return lines


def rules(jar: zipfile.ZipFile) -> list[str]:
    text = jar.read(LANG).decode("utf-8")
    keys = [line.split("=", 1)[0].strip() for line in text.splitlines() if "=" in line and not line.startswith("#")]
    lines = ["[[lang]]", f"from = {quote(LANG)}", "rules = ["]
    for key in keys:
        legacy = LEGACY_NAME.match(key)
        if not legacy:
            continue
        if any(other != key and other.startswith(key) for other in keys):
            raise SystemExit(f"{key} is a prefix of another key, an exact rule would catch both")
        lines.append(f"    {{ from = {quote(key)}, to = {quote(f'{legacy[1]}.{MODID}.{legacy[2]}.name')} }},")
    lines.append(f"    {{ from = \"\", to = {quote(MODID + '.')} }},")
    return lines + ["]", ""]


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    jar = Path(sys.argv[1])
    sha = hashlib.sha256(jar.read_bytes()).hexdigest()
    with zipfile.ZipFile(jar) as opened:
        names = sorted(opened.namelist())
        lines = ["# generated by tools/recipe.py from the pinned jar", ""]
        lines += ["[[download]]", f"name = {quote(jar.name)}", f"sha256 = [{quote(sha)}]", ""]
        lines += copies(names)
        lines += rules(opened)
    RECIPE.write_text("\n".join(lines).rstrip("\n") + "\n")
    print(f"wrote {RECIPE}")


if __name__ == "__main__":
    main()
