# TextureOilFX and TextureOilFlowFX paint these every client tick, the files only hold the sprites near black until then
OIL_SPRITES = ["oil_still", "oil_flow"]
OIL_FILL = "0a0a0aff"


def source(path: str) -> str:
    return next(name for folder, name in FOLDER_SOURCE.items() if path.startswith(folder))


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cut(sheet: str, target: str, tiles: dict[int, str]) -> list[str]:
    lines = ["[[slice]]", f"source = {quote(source(sheet))}", f"from = {quote(SHEET_ROOT + sheet)}",
             f"to = {quote(target)}", f"tile = {TILE}", "", "[slice.tiles]"]
    lines += [f"{slot} = {quote(name)}" for slot, name in sorted(tiles.items())]
    return lines + [""]


def main() -> None:
    lines = ["# generated by tools/recipe.py, edit the tables there", ""]
    for name, sha in DOWNLOADS.items():
        lines += ["[[download]]", f"name = {quote(name)}", f"sha256 = [{quote(sha)}]", ""]
    for sheet, target in GUIS.items():
        path = target if target.startswith("textures/") else f"textures/{target}"
        lines += ["[[copy]]", f"source = {quote(source(sheet))}", f"from = {quote(SHEET_ROOT + sheet)}",
                  f"to = {quote(path)}", ""]
    lines += cut("core/gui/block_textures.png", "textures/block/", BLOCKS)
    lines += cut("core/gui/item_textures.png", "textures/item/", ITEMS)
    for name in OIL_SPRITES:
        lines += ["[[compose]]", f"to = {quote(f'textures/block/{name}.png')}", f"canvas = [{TILE}, {TILE}]",
                  f"fill = {quote(OIL_FILL)}", ""]
    RECIPE.write_text("\n".join(lines).rstrip("\n") + "\n")
    print(f"wrote {RECIPE}")


if __name__ == "__main__":
    main()
